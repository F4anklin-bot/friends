export interface WordPair {
  id: string
  good: string
  fake: string
  difficulty: number
}

export interface ImpostorCategory {
  id: string
  name: string
  icon: string
  color: string
  pairs: WordPair[]
}

function pairs(categoryId: string, items: [string, string, number][]): WordPair[] {
  return items.map(([good, fake, difficulty], index) => ({
    id: `${categoryId}-${index}`,
    good,
    fake,
    difficulty,
  }))
}

